#!/usr/bin/env python3
"""Grade local artifacts against a maintainer-controlled synthetic ground-truth spec.

Usage: python evals/grade_outcomes.py RUN_DIR --expectations evals/outcomes-jump.json
Network-free: retain each source locally and cite its RUN_DIR-relative path in evidence.json.
This checks artifacts, not authorship, genuine tool execution, Studio behavior or agent benefit.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parents[1] / 'skills/roblox-game-remaker/scripts'
sys.path.insert(0, str(SCRIPTS))
import breakdown_check  # noqa: E402


def local_file(root: Path, name) -> bool:
    if not isinstance(name, str) or not name.strip():
        return False
    path = (root / name).resolve()
    return root.resolve() in path.parents and path.is_file() and path.stat().st_size > 0


def number(value) -> bool:
    return not isinstance(value, bool) and isinstance(value, (int, float)) and math.isfinite(value)


def grade(root: Path, expected: dict) -> list[tuple[str, bool]]:
    checks = []
    files, metrics = expected.get('files'), expected.get('metrics')
    if not isinstance(files, list) or not files or not isinstance(metrics, dict) or not metrics:
        return [('expectations require nonempty files and metrics', False)]
    checks += [(f'artifact {name}', local_file(root, name)) for name in files]
    remake = root / 'remake'
    try:
        result = breakdown_check.check_workspace(remake)
    except (OSError, ValueError, TypeError, KeyError, AttributeError) as exc:
        return checks + [(f'valid breakdown and ledgers ({exc})', False)]
    checks.append(('breakdown_check strict (no warnings or errors)', not result['errors'] and not result['warnings']))
    ev, ms = result['evidence'], result['measurements']
    checks.append(('nonempty evidence and measurements', bool(ev) and bool(ms)))
    for mid, m in ms.items():
        sources = m.get('evidence') or []
        checks.append((f'{mid} accessible retained sources', bool(sources) and all(
            e in ev and ev[e].get('accessible') is True and local_file(root, ev[e].get('source')) for e in sources)))
        if isinstance(m.get('value'), (int, float)):
            checks.append((f'{mid} finite value and uncertainty', number(m.get('value')) and number(m.get('uncertainty'))
                           and m['uncertainty'] >= 0))
    for metric, truth in metrics.items():
        if not isinstance(truth, dict) or not number(truth.get('value')) or not number(truth.get('tolerance')) or truth['tolerance'] < 0 or not truth.get('unit'):
            checks.append((f'{metric} valid independent expectation', False))
            continue
        candidates = [m for m in ms.values() if m.get('metric') == metric]
        # Duplicate metric IDs are ambiguous: don't let an old good value hide the run's bad one.
        ok = len(candidates) == 1
        if ok:
            m = candidates[0]
            ok = (number(m.get('value')) and number(m.get('uncertainty'))
                  and 0 <= m['uncertainty'] <= truth['tolerance']
                  and abs(m['value'] - truth['value']) <= truth['tolerance'] and m.get('unit') == truth['unit'])
        checks.append((f'{metric} within ground-truth tolerance', ok))
    return checks


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('run', type=Path)
    ap.add_argument('--expectations', type=Path, required=True, help='trusted benchmark spec, not generated by the evaluated agent')
    ap.add_argument('--json', action='store_true')
    args = ap.parse_args()
    try:
        expected = json.loads(args.expectations.read_text(encoding='utf-8'))
        checks = grade(args.run, expected)
    except (OSError, ValueError, TypeError, AttributeError) as exc:
        checks = [(f'valid outcome inputs ({exc})', False)]
    ok = bool(checks) and all(passed for _, passed in checks)
    if args.json:
        print(json.dumps({'tool': 'grade_outcomes', 'pass': ok, 'checks': [{'check': k, 'pass': v} for k, v in checks]}, indent=2))
    else:
        for label, passed in checks:
            print(f"{'PASS' if passed else 'FAIL'}: {label}")
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
